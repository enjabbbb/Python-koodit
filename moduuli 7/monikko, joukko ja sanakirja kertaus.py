#Luo monikko

hedelmat = ("omena", "banaani", "appelsiini")

#Tulostetaan koko monikko
print(hedelmat)

#Tulostetaan ensimmäinen arvo (indeksi 0)
print(hedelmat[0])

#Tulosta monikon pituus
print(len(hedelmat))

# Luo joukko
hedelmat = {"omena", "banaani", "appelsiini"}

# Tulosta koko joukko
print(hedelmat)

hedelmat.add("Ananas")
print(hedelmat)

# Tulosta joukon pituus
print(len(hedelmat))

# Luo sanakirja
hedelmat = {
    "eka": "omena",
    "toka": "banaani",
    "kolmas": "appelsiini"
}

# Tulosta koko sanakirja
print(hedelmat)

# Tulosta ensimmäinen arvo avaimen avulla
print(hedelmat["eka"])

# Tulosta sanakirjan pituus
print(len(hedelmat))
